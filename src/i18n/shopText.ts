export function shopText(locale: string, text: string, values?: Record<string, string | number>) {
  const index = ({ zh: 0, ja: 1, ko: 2 } as Record<string, number>)[locale];
  let result = index === undefined ? (copy[text] && text.includes(" / ") ? text.split(" / ")[0] : text) : copy[text]?.[index] ?? text;
  for (const [key, value] of Object.entries(values ?? {})) result = result.replaceAll(`{${key}}`, () => String(value));
  return result;
}
